#!/usr/bin/env node
/**
 * Copies SEO/OG/hreflang/JSON-LD tags from the gzip-loaded document into the
 * outer <head> of the self-loader pages (index.html),
 * so crawlers that do not run JavaScript (KakaoTalk, Facebook, Twitter, ...) see them.
 *
 * The loader still replaces the whole document via document.write, so the
 * duplicated tags vanish once the game boots. Idempotent: rewrites the block
 * between the static-seo markers.
 *
 * Usage: node scripts/add-static-seo-head.js [--check]
 */
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const ROOT = path.join(__dirname, '..');
// Only the ko root page is a gzip self-loader; the language pages are plain HTML already.
const PAGES = ['index.html'];
const START = '<!-- static-seo:start (generated by scripts/add-static-seo-head.js) -->';
const END = '<!-- static-seo:end -->';

function decodeLoader(html) {
    const m = html.match(/var b64 = "([A-Za-z0-9+/=]+)"/);
    if (!m) return null;
    return zlib.gunzipSync(Buffer.from(m[1], 'base64')).toString('utf8');
}

function extractHead(decoded) {
    const head = decoded.slice(decoded.indexOf('<head>'), decoded.indexOf('</head>'));
    const tags = [];
    const re = /<title>[^<]*<\/title>|<meta\b[^>]*>|<link\b[^>]*>|<script type="application\/ld\+json">[\s\S]*?<\/script>/g;
    let m;
    while ((m = re.exec(head))) {
        const t = m[0];
        if (/^<title/.test(t) || /^<script/.test(t)) { tags.push(t); continue; }
        if (/charset=|name="viewport"|http-equiv=/.test(t)) continue;
        if (/^<meta\b/.test(t) && /(name="(description|keywords|robots|googlebot|author|theme-color)"|property="og:|name="twitter:)/.test(t)) { tags.push(t); continue; }
        if (/^<link\b/.test(t) && /rel="(canonical|alternate)"/.test(t)) tags.push(t);
    }
    return tags;
}

let changed = 0;
for (const rel of PAGES) {
    const file = path.join(ROOT, rel);
    let html = fs.readFileSync(file, 'utf8');
    const decoded = decodeLoader(html);
    if (!decoded) { console.error(`skip ${rel}: no gzip loader found`); continue; }
    const tags = extractHead(decoded);
    if (!tags.some(t => /^<title/.test(t)) || !tags.some(t => /name="description"/.test(t)) || !tags.some(t => /og:title/.test(t))) {
        throw new Error(`${rel}: decoded head is missing title/description/og:title`);
    }
    const title = tags.find(t => /^<title/.test(t));
    const block = `${START}\n${tags.filter(t => t !== title).map(t => '    ' + t.replace(/\n\s*/g, '\n    ')).join('\n')}\n    ${END}`;
    html = html.replace(/<title>[^<]*<\/title>/, title);
    const existing = new RegExp(`\\s*${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`);
    html = existing.test(html) ? html.replace(existing, `\n    ${block}`) : html.replace('</head>', `    ${block}\n</head>`);
    const before = fs.readFileSync(file, 'utf8');
    if (html !== before) {
        changed++;
        if (process.argv.includes('--check')) { console.error(`${rel}: static SEO head is out of date`); continue; }
        fs.writeFileSync(file, html, 'utf8');
        console.log(`updated ${rel} (${tags.length} tags)`);
    }
}
if (process.argv.includes('--check') && changed) process.exit(1);
console.log(changed ? `${changed} page(s) changed` : 'static SEO head already up to date');
